"""P2 — AST parsing: one Python file -> entities + raw relation sites + its name bindings.

Nothing is resolved here; the parser only records WHAT is used WHERE. `graph_builder` (P3) then decides,
with the whole repository in view, whether each site's target is syntactically determined.

Rules [ours, CLAUDE.md §3.2]:
- Entities: the file, classes (incl. nested classes), functions/methods. Functions/classes defined INSIDE a
  function are folded into that function (their code and relations belong to it).
- Relation sites are attributed to the innermost entity; module-level code belongs to the file entity.
- Identical sites inside one entity (same kind + same text) are stored once with a `count`.
"""

import ast
import io
import re
import tokenize
import warnings
from dataclasses import dataclass, field

from traceagent.models.graph import Entity

# Only an explicit header COMMENT saying the WHOLE file is generated. A looser rule ("generated by" anywhere in the
# first lines) wrongly skipped matplotlib's pyplot.py ("the latter part is autogenerated") and an astropy docstring.
GENERATED_RE = re.compile(
    r"^#.*(do not edit|@generated|this (file|module) (is|was|has been) (automatically |auto-?)?generated)",
    re.IGNORECASE,
)
TEST_DIR_NAMES = {"test", "tests", "testing"}


def is_test_path(path: str) -> bool:
    parts = path.split("/")
    name = parts[-1]
    return (
        any(p in TEST_DIR_NAMES for p in parts[:-1])
        or name.startswith("test_")
        or name.endswith("_test.py")
        or name == "conftest.py"
    )


@dataclass(frozen=True)
class ImportBinding:
    """`import a.b as x` -> x: (module="a.b", name=None); `from m import n as y` -> y: (module="m", name="n")."""

    module: str
    name: str | None


@dataclass
class RawSite:
    src: str  # entity id
    kind: str  # "Calls" | "Imports" | "Inherits" | "References"
    line: int
    col: int  # UTF-16 column of the target-name token
    raw_text: str
    target_name: str
    chain: tuple[str, ...] | None = None  # ("os", "path", "join") for pure dotted names, else None
    binding: ImportBinding | None = None  # for Imports sites
    count: int = 1


@dataclass
class FileParse:
    path: str
    module: str  # dotted module name, e.g. "django.db.models.base"
    is_test: bool
    entities: list[Entity] = field(default_factory=list)
    contains: list[tuple[str, str]] = field(default_factory=list)  # (parent id, child id)
    sites: list[RawSite] = field(default_factory=list)
    top_defs: dict[str, str] = field(default_factory=dict)  # top-level class/function name -> entity id
    class_members: dict[str, dict[str, str]] = field(default_factory=dict)  # class id -> {member: id}
    imports: dict[str, ImportBinding] = field(default_factory=dict)  # module-level bindings
    local_imports: dict[str, dict[str, ImportBinding]] = field(default_factory=dict)  # entity id -> bindings
    locals: dict[str, set[str]] = field(default_factory=dict)  # function id -> locally bound names
    star_imports: list[str] = field(default_factory=list)  # modules of `from m import *` (absolute)
    module_vars: set[str] = field(default_factory=set)  # names assigned at module level (CONST = 1)


class SkipFile(Exception):
    """Raised when a file must be skipped; `reason` goes to the skip log."""

    def __init__(self, reason: str, detail: str = ""):
        super().__init__(f"{reason}: {detail}")
        self.reason, self.detail = reason, detail


# ----------------------------------------------------------------------------- helpers

def decode_source(data: bytes) -> str:
    """Decode with the PEP 263 coding cookie (default UTF-8)."""
    try:
        enc, _ = tokenize.detect_encoding(io.BytesIO(data).readline)
        return data.decode(enc)
    except (SyntaxError, LookupError, UnicodeDecodeError) as exc:
        raise SkipFile("decode_error", str(exc)) from exc


def chain_of(expr: ast.expr) -> list[str] | None:
    """`a.b.c` -> ["a", "b", "c"]; anything that is not a pure dotted name -> None."""
    parts: list[str] = []
    while isinstance(expr, ast.Attribute):
        parts.append(expr.attr)
        expr = expr.value
    if isinstance(expr, ast.Name):
        parts.append(expr.id)
        return parts[::-1]
    return None


def resolve_relative(module: str, is_package: bool, level: int, name: str | None) -> str:
    """Absolute module for `from <level dots><name> import ...` written in `module`."""
    if level == 0:
        return name or ""
    parts = module.split(".") if module else []
    pkg = parts if is_package else parts[:-1]
    base = pkg[: len(pkg) - (level - 1)] if level - 1 <= len(pkg) else []
    return ".".join(base + ([name] if name else []))


def bound_names(fn: ast.FunctionDef | ast.AsyncFunctionDef | ast.Lambda) -> set[str]:
    """Names bound locally in a function (params, assignments, loop vars, nested defs, ...), minus globals."""
    names: set[str] = set()
    a = fn.args
    for arg in [*a.posonlyargs, *a.args, *a.kwonlyargs, a.vararg, a.kwarg]:
        if arg is not None:
            names.add(arg.arg)
    declared_global: set[str] = set()
    for node in ast.walk(fn):
        if isinstance(node, ast.Name) and isinstance(node.ctx, (ast.Store, ast.Del)):
            names.add(node.id)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and node is not fn:
            names.add(node.name)
        elif isinstance(node, ast.arg):
            names.add(node.arg)
        elif isinstance(node, ast.ExceptHandler) and node.name:
            names.add(node.name)
        elif isinstance(node, (ast.Global, ast.Nonlocal)):
            declared_global.update(node.names)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            pass  # import aliases are handled as local import bindings, not as plain locals
    return names - declared_global


# ----------------------------------------------------------------------------- parser

class _FileParser:
    def __init__(self, path: str, module: str, text: str, is_package: bool):
        self.fp = FileParse(path=path, module=module, is_test=is_test_path(path))
        self.lines = text.split("\n")
        self.is_package = is_package
        self._site_index: dict[tuple[str, str, str], RawSite] = {}
        self._seen_ids: set[str] = set()

    # ---- positions
    def _utf16_col(self, lineno: int, byte_col: int) -> int:
        line = self.lines[lineno - 1] if 0 < lineno <= len(self.lines) else ""
        prefix = line.encode("utf-8")[:byte_col].decode("utf-8", errors="replace")
        return sum(2 if ord(c) > 0xFFFF else 1 for c in prefix)

    def _name_token_pos(self, expr: ast.expr) -> tuple[int, int]:
        """Position of the LAST name token: `run` in `obj.run`, `x` in `x`."""
        if isinstance(expr, ast.Attribute):
            line, byte_col = expr.end_lineno, expr.end_col_offset - len(expr.attr.encode("utf-8"))
        else:
            line, byte_col = expr.lineno, expr.col_offset
        return line, self._utf16_col(line, byte_col)

    # ---- recording
    def _add_site(self, src: str, kind: str, expr: ast.expr | None, raw: str, target: str,
                  chain: list[str] | None = None, binding: ImportBinding | None = None,
                  pos: tuple[int, int] | None = None) -> None:
        raw = raw if len(raw) <= 200 else raw[:197] + "..."
        key = (src, kind, raw)
        if key in self._site_index:
            self._site_index[key].count += 1
            return
        line, col = pos if pos else self._name_token_pos(expr)  # type: ignore[arg-type]
        site = RawSite(src, kind, line, col, raw, target, tuple(chain) if chain else None, binding)
        self._site_index[key] = site
        self.fp.sites.append(site)

    def _new_entity(self, node, kind: str, qual: str, parent: str) -> str:
        eid = f"{self.fp.path}::{qual}"
        start = min([d.lineno for d in node.decorator_list] + [node.lineno])
        if eid in self._seen_ids:  # duplicate definition (e.g. property setter) -> suffix with line
            eid = f"{eid}@{start}"
        self._seen_ids.add(eid)
        if kind == "class":
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            sig = f"class {node.name}({bases})" if bases else f"class {node.name}"
        else:
            prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
            sig = f"{prefix} {node.name}({ast.unparse(node.args)})"
            if node.returns is not None:
                sig += f" -> {ast.unparse(node.returns)}"
        self.fp.entities.append(Entity(
            id=eid, type=kind, name=node.name, qualified_name=qual, file_path=self.fp.path,
            start_line=start, end_line=node.end_lineno, signature=sig, is_test=self.fp.is_test,
        ))
        self.fp.contains.append((parent, eid))
        return eid

    # ---- imports
    def _record_import(self, node: ast.Import | ast.ImportFrom, owner: str,
                       table: dict[str, ImportBinding]) -> None:
        pos = (node.lineno, self._utf16_col(node.lineno, node.col_offset))
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.asname:
                    b = ImportBinding(alias.name, None)
                    table[alias.asname] = b
                else:  # `import a.b.c` binds `a`, but the statement imports module a.b.c
                    table[alias.name.split(".")[0]] = ImportBinding(alias.name.split(".")[0], None)
                    b = ImportBinding(alias.name, None)
                self._add_site(owner, "Imports", None, f"import {alias.name}", alias.name.split(".")[-1],
                               binding=b, pos=pos)
        else:
            module = resolve_relative(self.fp.module, self.is_package, node.level, node.module)
            for alias in node.names:
                if alias.name == "*":
                    self.fp.star_imports.append(module)
                    b = ImportBinding(module, None)
                    self._add_site(owner, "Imports", None, f"from {module} import *", module.split(".")[-1],
                                   binding=b, pos=pos)
                    continue
                b = ImportBinding(module, alias.name)
                table[alias.asname or alias.name] = b
                self._add_site(owner, "Imports", None, f"from {module} import {alias.name}", alias.name,
                               binding=b, pos=pos)

    # ---- expressions (calls / references)
    def _collect_refs(self, node: ast.AST, owner: str, local_table: dict[str, ImportBinding]) -> None:
        """Walk `node`, recording Calls and References sites; nested defs here are folded into `owner`."""
        stack = [node]
        while stack:
            cur = stack.pop()
            if isinstance(cur, (ast.Import, ast.ImportFrom)):
                self._record_import(cur, owner, local_table)
                continue
            if isinstance(cur, ast.Call):
                func = cur.func
                ch = chain_of(func)
                if isinstance(func, (ast.Name, ast.Attribute)):
                    raw = ".".join(ch) if ch else ast.unparse(func)
                    target = func.id if isinstance(func, ast.Name) else func.attr
                    self._add_site(owner, "Calls", func, raw, target, ch)
                    if isinstance(func, ast.Attribute) and ch is None:
                        stack.append(func.value)  # e.g. self.get(x).run(): still visit self.get(x)
                else:
                    stack.append(func)
                stack.extend(cur.args)
                stack.extend(k.value for k in cur.keywords)
                continue
            if isinstance(cur, (ast.Name, ast.Attribute)) and isinstance(cur.ctx, ast.Load):
                ch = chain_of(cur)
                if ch is not None:
                    self._add_site(owner, "References", cur, ".".join(ch), ch[-1], ch)
                    continue
                if isinstance(cur, ast.Attribute):  # e.g. foo().bar -> visit foo()
                    stack.append(cur.value)
                    continue
            stack.extend(ast.iter_child_nodes(cur))

    # ---- statements
    def _visit_def(self, node, owner: str, prefix: str) -> None:
        if isinstance(node, ast.ClassDef):
            cid = self._new_entity(node, "class", prefix + node.name, owner)
            if not prefix:
                self.fp.top_defs.setdefault(node.name, cid)
            else:
                self.fp.class_members.setdefault(owner, {}).setdefault(node.name, cid)
            for base in node.bases:
                ch = chain_of(base)
                if ch is not None:
                    self._add_site(cid, "Inherits", base, ".".join(ch), ch[-1], ch)
                else:
                    self._collect_refs(base, cid, {})
            for item in [*node.decorator_list, *(k.value for k in node.keywords)]:
                self._collect_refs(item, cid, {})
            self._visit_body(node.body, cid, prefix + node.name + ".", in_class=True)
        else:
            fid = self._new_entity(node, "function", prefix + node.name, owner)
            if not prefix:
                self.fp.top_defs.setdefault(node.name, fid)
            else:
                self.fp.class_members.setdefault(owner, {}).setdefault(node.name, fid)
            self.fp.locals[fid] = bound_names(node)
            table = self.fp.local_imports.setdefault(fid, {})
            for item in [*node.decorator_list, node.args, *( [node.returns] if node.returns else [])]:
                self._collect_refs(item, fid, table)
            for stmt in node.body:
                self._collect_refs(stmt, fid, table)

    def _visit_body(self, body: list[ast.stmt], owner: str, prefix: str, in_class: bool) -> None:
        table = self.fp.imports if not in_class else self.fp.local_imports.setdefault(owner, {})
        for node in body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                self._visit_def(node, owner, prefix)
            elif isinstance(node, (ast.Import, ast.ImportFrom)):
                self._record_import(node, owner, table)
            elif isinstance(node, (ast.If, ast.Try, ast.With, ast.AsyncWith, ast.For, ast.AsyncFor, ast.While)):
                # defs under `if TYPE_CHECKING:` / `try: import x except ImportError:` stay at this level
                for expr_field in ("test", "iter", "target"):
                    if getattr(node, expr_field, None) is not None:
                        self._collect_refs(getattr(node, expr_field), owner, table)
                for item in getattr(node, "items", []):
                    self._collect_refs(item, owner, table)
                for field_name in ("body", "orelse", "finalbody"):
                    self._visit_body(getattr(node, field_name, []) or [], owner, prefix, in_class)
                for h in getattr(node, "handlers", []):
                    if h.type is not None:
                        self._collect_refs(h.type, owner, table)
                    self._visit_body(h.body, owner, prefix, in_class)
            else:
                self._collect_refs(node, owner, table)

    def parse(self, tree: ast.Module) -> FileParse:
        n_lines = len(self.lines)
        self.fp.entities.append(Entity(
            id=self.fp.path, type="file", name=self.fp.path.split("/")[-1], qualified_name="",
            file_path=self.fp.path, start_line=1, end_line=n_lines, signature="", is_test=self.fp.is_test,
        ))
        self._seen_ids.add(self.fp.path)
        self._visit_body(tree.body, self.fp.path, "", in_class=False)
        # module-level variables (not entities, but `from m import CONST` clearly points into this file)
        stack: list[ast.AST] = list(tree.body)
        while stack:
            node = stack.pop()
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Lambda)):
                continue
            if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store):
                self.fp.module_vars.add(node.id)
            stack.extend(ast.iter_child_nodes(node))
        return self.fp


def parse_file(path: str, data: bytes, module: str, is_package: bool, max_kb: int = 1024) -> FileParse:
    """Parse one file. Raises SkipFile(reason) for files we do not use."""
    if len(data) > max_kb * 1024:
        raise SkipFile("too_large", f"{len(data) // 1024} KB")
    text = decode_source(data)
    for head_line in text.split("\n", 5)[:5]:
        if GENERATED_RE.search(head_line.strip()):
            raise SkipFile("generated", head_line.strip()[:80])
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")  # e.g. "invalid escape sequence" in old code
            tree = ast.parse(text)
    except (SyntaxError, ValueError, RecursionError, MemoryError) as exc:
        raise SkipFile("syntax_error", str(exc)[:120]) from exc
    return _FileParser(path, module, text, is_package).parse(tree)
