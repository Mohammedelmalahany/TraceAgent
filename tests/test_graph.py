@pytest.fixture(scope="module")
def g():
    return build_from_sources({k: v.encode() for k, v in TOY.items()})


def edges(g, kind):
    return {(e.src, e.dst) for e in g.edges if e.type == kind}


def sites(g, kind):
    return {(s.src, s.raw_text) for s in g.sites if s.kind == kind}


M = "pkg/models.py"
U = "pkg/utils.py"
T = "tests/test_models.py"


def test_module_names_follow_packages():
    mods = module_names(["pkg/__init__.py", "pkg/utils.py", "lib/matplotlib/__init__.py", "lib/matplotlib/axes.py",
                         "setup.py"])
    assert mods["pkg/__init__.py"] == ("pkg", True)
    assert mods["pkg/utils.py"] == ("pkg.utils", False)
    assert mods["lib/matplotlib/axes.py"] == ("matplotlib.axes", False)  # `lib/` is not a package
    assert mods["setup.py"] == ("setup", False)


def test_entities_and_folding(g):
    ids = {e.id for e in g.entities}
    assert {M, f"{M}::Base", f"{M}::Model", f"{M}::Model.save", f"{M}::make", f"{U}::helper"} <= ids
    assert f"{U}::helper.inner" not in ids  # nested function folded into helper
    assert f"{M}::Model.size" in ids and f"{M}::Model.size@27" in ids  # property setter duplicate
    assert next(e for e in g.entities if e.id == f"{M}::Model.size").start_line == 23  # decorator included
    assert next(e for e in g.entities if e.id == f"{M}::make").signature == "def make(obj)"
    assert next(e for e in g.entities if e.id == T).is_test


def test_skips_are_logged(g):
    reasons = {s["file"]: s["reason"] for s in g.skipped}
    assert reasons == {"pkg/old.py": "syntax_error", "pkg/gen.py": "generated"}
    assert g.stats.files_total == 6 and g.stats.files_parsed == 4  # README.md is not .py


def test_contains(g):
    c = edges(g, "Contains")
    assert (M, f"{M}::Model") in c and (f"{M}::Model", f"{M}::Model.save") in c
    assert (M, f"{M}::Model.save") not in c  # methods hang under their class, not the file


def test_inherits_resolved(g):
    assert edges(g, "Inherits") == {(f"{M}::Model", f"{M}::Base")}


def test_calls_resolved_only_when_syntactically_determined(g):
    c = edges(g, "Calls")
    assert (f"{M}::Base.save", f"{U}::helper") in c  # explicit relative import
    assert (f"{M}::make", f"{M}::Model") in c  # same-file class
    assert (f"{M}::make", f"{M}::Model.validate") in c  # member defined directly in a known class
    assert (f"{T}::test_it", f"{U}::helper") in c  # module attribute chain pkg.utils.helper
    assert (f"{T}::test_it", f"{M}::make") in c  # star import from a repo module


def test_ambiguous_calls_become_unresolved_sites_not_guesses(g):
    s = sites(g, "Calls")
    assert (f"{M}::Model.save", "self.validate") in s  # subclass might override
    assert (f"{M}::make", "obj.run") in s  # runtime type of obj
    assert any(src == f"{M}::Model.save" and raw == "super().save" for src, raw in s)
    assert any(src == f"{T}::test_it" and raw.endswith(".save") for src, raw in s)  # Model().save
    # and no guessed edge from make -> anything called "run"
    assert not any(src == f"{M}::make" and dst.endswith(".run") for src, dst in edges(g, "Calls"))


def test_external_and_local_are_not_stored(g):
    assert g.stats.external.get("Calls", 0) >= 2  # os.path.join, print
    assert g.stats.external.get("Imports", 0) == 1  # import os
    assert g.stats.dropped_local >= 1  # `value`, `m`
    all_targets = {dst for _, dst in edges(g, "Calls")} | {raw for _, raw in sites(g, "Calls")}
    assert "print" not in all_targets and "os.path.join" not in all_targets


def test_imports(g):
    i = edges(g, "Imports")
    assert (M, f"{U}::helper") in i
    assert (M, U) in i  # CONST is a module variable -> the file
    assert (T, f"{M}::Model") in i  # re-exported through pkg/__init__.py
    assert (T, U) in i  # import pkg.utils
    assert ("pkg/__init__.py", f"{M}::Model") in i


def test_references(g):
    r = edges(g, "References")
    assert (f"{M}::make", f"{U}::helper") in r  # `return helper`
    assert (f"{M}::Model.validate", U) in r  # CONST -> module variable of utils (via import)


def test_partly_generated_file_is_not_skipped():
    # header of matplotlib's pyplot.py: only PART of it is generated -> must be parsed
    src = "# Note: The first part of this file can be modified in place, but the latter\n" \
          "# part is autogenerated by the boilerplate.py script.\n\ndef figure():\n    pass\n"
    doc = '"""Fix checksums originally generated by old tools."""\n\ndef main():\n    pass\n'
    g2 = build_from_sources({"pyplot.py": src.encode(), "fitscheck.py": doc.encode()})
    assert not g2.skipped
    assert {"pyplot.py::figure", "fitscheck.py::main"} <= {e.id for e in g2.entities}


def test_star_reexport_is_followed():
    # like django/forms/__init__.py: `from django.forms.fields import *`
    srcs = {
        "lib/__init__.py": "from lib.fields import *\n",
        "lib/fields.py": "class URLField:\n    pass\n",
        "app.py": "from lib import URLField\n\ndef f():\n    return URLField()\n",
    }
    g2 = build_from_sources({k: v.encode() for k, v in srcs.items()})
    assert ("app.py", "lib/fields.py::URLField") in edges(g2, "Imports")
    assert ("app.py::f", "lib/fields.py::URLField") in edges(g2, "Calls")
    assert not sites(g2, "Imports")


def test_site_position_points_at_target_name_in_utf16():
    src = 'def f(obj):\n    t = "\U0001F600"; obj.run()\n'
    fp = parse_file("m.py", src.encode(), "m", False)
    site = next(s for s in fp.sites if s.raw_text == "obj.run")
    line = src.split("\n")[1]
    assert site.line == 2
    # `run` starts after: 4 spaces + 't = "' (5) + emoji (2 UTF-16 units) + '"; obj.' (7)
    assert site.col == 4 + 5 + 2 + 7
    assert line[site.col - 1:].startswith("run")  # Python str index differs by 1 (emoji = 1 char)
